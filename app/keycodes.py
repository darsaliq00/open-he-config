"""HID keyboard usage codes: label, PS/2 set-1 scan code (0xE0xx = extended) and keycap width.

Used to draw an RK board from the key map the keyboard reports itself, and to
let the key blocker recognise those keys.
"""

_KEYS = {
    0x29: ("Esc", 0x01), 0x3A: ("F1", 0x3B), 0x3B: ("F2", 0x3C), 0x3C: ("F3", 0x3D), 0x3D: ("F4", 0x3E),
    0x3E: ("F5", 0x3F), 0x3F: ("F6", 0x40), 0x40: ("F7", 0x41), 0x41: ("F8", 0x42), 0x42: ("F9", 0x43),
    0x43: ("F10", 0x44), 0x44: ("F11", 0x57), 0x45: ("F12", 0x58),
    0x35: ("`", 0x29), **{0x1E + i: (str((i + 1) % 10), 0x02 + i) for i in range(10)},
    0x2D: ("-", 0x0C), 0x2E: ("=", 0x0D), 0x2A: ("Bksp", 0x0E),
    0x2B: ("Tab", 0x0F), 0x2F: ("[", 0x1A), 0x30: ("]", 0x1B), 0x31: ("\\", 0x2B),
    0x39: ("Caps", 0x3A), 0x33: (";", 0x27), 0x34: ("'", 0x28), 0x28: ("Enter", 0x1C),
    0xE1: ("Shift", 0x2A), 0x36: (",", 0x33), 0x37: (".", 0x34), 0x38: ("/", 0x35), 0xE5: ("Shift", 0x36),
    0xE0: ("Ctrl", 0x1D), 0xE3: ("Win", 0xE05B), 0xE2: ("Alt", 0x38), 0x2C: ("Space", 0x39),
    0xE6: ("Alt", 0xE038), 0xE7: ("Win", 0xE05C), 0x65: ("Menu", 0xE05D), 0xE4: ("Ctrl", 0xE01D),
    0x46: ("Prt", 0xE037), 0x47: ("ScrLk", 0x46), 0x48: ("Pause", 0x45),
    0x49: ("Ins", 0xE052), 0x4A: ("Home", 0xE047), 0x4B: ("PgUp", 0xE049), 0x4C: ("Del", 0xE053),
    0x4D: ("End", 0xE04F), 0x4E: ("PgDn", 0xE051),
    0x4F: ("Right", 0xE04D), 0x50: ("Left", 0xE04B), 0x51: ("Down", 0xE050), 0x52: ("Up", 0xE048),
    0x53: ("NumLk", 0x45), 0x54: ("KP /", 0xE035), 0x55: ("KP *", 0x37), 0x56: ("KP -", 0x4A),
    0x57: ("KP +", 0x4E), 0x58: ("KP Ent", 0xE01C), 0x63: ("KP .", 0x53),
    0x59: ("KP 1", 0x4F), 0x5A: ("KP 2", 0x50), 0x5B: ("KP 3", 0x51), 0x5C: ("KP 4", 0x4B),
    0x5D: ("KP 5", 0x4C), 0x5E: ("KP 6", 0x4D), 0x5F: ("KP 7", 0x47), 0x60: ("KP 8", 0x48),
    0x61: ("KP 9", 0x49), 0x62: ("KP 0", 0x52),
}
# letters
_KEYS.update({0x04 + i: (chr(ord("A") + i), s) for i, s in enumerate(
    (0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32,
     0x31, 0x18, 0x19, 0x10, 0x13, 0x1F, 0x14, 0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C))})

FN = 0xF001

_WIDTH = {0x2A: 2, 0x2B: 1.5, 0x31: 1.5, 0x39: 1.75, 0x28: 2.25, 0xE1: 2.25, 0xE5: 1.75, 0x2C: 6.25,
          0xE0: 1.25, 0xE3: 1.25, 0xE2: 1.25, 0x58: 1, 0x62: 2}


def describe(code: int) -> tuple[str, int | None, float]:
    """(label, scan code or None, width in key units) for a key code from the keyboard's key map."""
    if code in (FN, 0x01):   # the key map reports Fn as 0x01
        return "Fn", None, 1
    label, scan = _KEYS.get(code, (f"{code:02X}", None))
    return label, scan, _WIDTH.get(code, 1)
